dry = "--dry" in sys.argv
cache, report = {}, []
for rel, old, new in RULES:
    if old == new:
        report.append(("SKIP", rel, old[:40], 0))
        continue
    p = ROOT / rel
    if p not in cache:
        cache[p] = p.read_text(encoding="utf-8")
    n = cache[p].count(old)
    if n == 0 and new in cache[p]:
        report.append(("DONE", rel, old[:44], 0))
        continue
    report.append(("OK" if n else "MISS", rel, old[:44], n))
    if n:
        cache[p] = cache[p].replace(old, new)

bad = [r for r in report if r[0] == "MISS"]
for row in report:
    print("%-4s %-38s n=%d  %s" % (row[0], row[1], row[3], row[2]))
print("\n命中 %d / 未命中 %d" % (len(report) - len(bad), len(bad)))
if dry:
    sys.exit(1 if bad else 0)
if bad:
    print("存在未命中规则，未写盘。")
    sys.exit(1)
for p, txt in cache.items():
    p.write_text(txt, encoding="utf-8")
print("已写盘 %d 个文件。" % len(cache))
