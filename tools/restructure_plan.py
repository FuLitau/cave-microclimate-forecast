def split_blocks(text: str) -> tuple[str, dict[str, str]]:
    """按 `## ` 顶层标题切分，返回 (前言, {标题行: 完整块})。"""
    parts = re.split(r"(?m)^(?=## )", text)
    head = parts[0]
    blocks: dict[str, str] = {}
    order: list[str] = []
    for p in parts[1:]:
        title = p.split("\n", 1)[0].strip()
        blocks[title] = p if p.endswith("\n") else p + "\n"
        order.append(title)
    return head, blocks


def retitle(block: str, old_title: str, new_title: str) -> str:
    lines = block.split("\n")
    assert lines[0].startswith("## "), lines[0]
    lines[0] = new_title
    assert old_title != new_title or True
    return "\n".join(lines)


def renumber(block: str, mapping: dict[str, str]) -> str:
    """把块内的 `### x.y ...` 按 mapping 重编号。mapping 的键形如 '3.1'。"""
    def repl(m: re.Match) -> str:
        num = m.group(1)
        if num in mapping:
            return f"### {mapping[num]} {m.group(2)}"
        return m.group(0)
    return re.sub(r"(?m)^### ([0-9]+\.[0-9]+) (.*)$", repl, block)


